#!/usr/bin/env node
// Regenerates public/robots.txt and public/sitemap.xml from VITE_APP_URL so
// the two files can never drift out of sync with your real domain. Runs
// automatically before `npm run dev` and `npm run build` (see package.json).
//
// You haven't bought a domain yet, so this currently falls back to the
// Vercel URL below. Once you do: set VITE_APP_URL in your .env (and in
// Vercel's project env vars) to the real domain — these two files, plus
// canonical/og:url tags in SEOHead.tsx, all follow automatically. Nothing
// else to hand-edit.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const FALLBACK_URL = "https://darasaone-tz.vercel.app"; // placeholder until a real domain is set

async function loadEnvUrl() {
  if (process.env.VITE_APP_URL) return process.env.VITE_APP_URL;
  try {
    const envFile = await readFile(path.resolve(".env"), "utf8");
    const match = envFile.match(/^VITE_APP_URL=(.*)$/m);
    if (match && match[1].trim()) return match[1].trim();
  } catch {
    // no .env yet locally — fine, Vercel builds read process.env directly
  }
  return null;
}

const resolvedUrl = await loadEnvUrl();
const siteUrl = (resolvedUrl || FALLBACK_URL).replace(/\/$/, "");

if (!resolvedUrl) {
  console.warn(
    `\n[generate-seo-files] VITE_APP_URL not set — using placeholder ${FALLBACK_URL}.\n` +
      `Set VITE_APP_URL once you've bought your domain, then re-run the build.\n`
  );
}

// Fixed routes only. Course pages (/courses/:id) are dynamic — generate
// their entries server-side from the `courses` table where
// status = 'published', or add a Supabase edge function that returns XML at
// /sitemap-courses.xml and list it below.
const routes = [
  { path: "/", changefreq: "weekly", priority: "1.0" },
  { path: "/courses", changefreq: "daily", priority: "0.9" },
  { path: "/tools", changefreq: "monthly", priority: "0.8" },
  { path: "/tools/quran", changefreq: "monthly", priority: "0.8" },
  { path: "/tools/prayer-times", changefreq: "monthly", priority: "0.7" },
  { path: "/tools/qibla", changefreq: "monthly", priority: "0.6" },
  { path: "/tools/tasbih", changefreq: "monthly", priority: "0.5" },
  { path: "/tools/ramadan", changefreq: "monthly", priority: "0.6" },
  { path: "/about", changefreq: "monthly", priority: "0.6" },
  { path: "/contact", changefreq: "monthly", priority: "0.5" },
];

const robotsTxt = `User-agent: *
Allow: /
Disallow: /account
Disallow: /teacher
Disallow: /reset-password

Sitemap: ${siteUrl}/sitemap.xml
`;

const sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Auto-generated by scripts/generate-seo-files.mjs from VITE_APP_URL.
  Do not hand-edit — edit VITE_APP_URL or the routes list in that script
  instead, then re-run npm run dev / npm run build.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes
  .map(
    (r) => `  <url>
    <loc>${siteUrl}${r.path}</loc>
    <changefreq>${r.changefreq}</changefreq>
    <priority>${r.priority}</priority>
  </url>`
  )
  .join("\n")}
</urlset>
`;

await writeFile(path.resolve("public/robots.txt"), robotsTxt);
await writeFile(path.resolve("public/sitemap.xml"), sitemapXml);
console.log(`[generate-seo-files] wrote public/robots.txt and public/sitemap.xml for ${siteUrl}`);
